import type { SidebarsConfig } from "@docusaurus/plugin-content-docs";
import { existsSync } from "node:fs";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";

// This runs in Node.js - Don't use client-side code here (browser APIs, JSX...)

const docsDir = process.env.TISSUUMAPS_DOCS;
if (!docsDir) {
  throw new Error(
    "Set TISSUUMAPS_DOCS to the docs folder of a TissUUmaps checkout, e.g. TISSUUMAPS_DOCS=../TissUUmaps/docs",
  );
}

/** Absolute path to the TissUUmaps docs previewed as the current version */
export const tissuumapsDocsPath = resolve(docsDir);

/** Sidebar items generated by typedoc next to the API markdown */
export function loadTypedocSidebar(
  docsPath: string,
): Extract<SidebarsConfig[string], unknown[]> {
  const sidebarFile = join(docsPath, "api", "typedoc-sidebar.cjs");
  if (!existsSync(sidebarFile)) {
    throw new Error(
      `${sidebarFile} not found, generate the API docs in TissUUmaps first (pnpm run build:docs)`,
    );
  }
  const require = createRequire(import.meta.url);
  return require(sidebarFile) as Extract<SidebarsConfig[string], unknown[]>;
}
